import { createHash } from 'node:crypto';
import { readImageDimensions } from './imageDimensions.js';
import { signMediaUrl } from '../../src/lib/references/mediaAccess.js';

type StorageError = { message?: string; status?: number | string; statusCode?: number | string };

export const imageSha256 = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');

/** The bucket is private; issue a bounded bearer URL only after route authorization. */
export const signedMediaUrl = (storage: any, path: string): Promise<string> => signMediaUrl(storage, path, 15 * 60);

/** Persist private object references without keeping the temporary bearer token. */
export const canonicalMediaUrl = (value: string, projectUrl = process.env.SUPABASE_URL || ''): string => {
  try {
    const url = new URL(value);
    const project = new URL(projectUrl);
    if (url.origin !== project.origin) return value;
    const match = url.pathname.match(/^\/storage\/v1\/(?:object|render\/image)\/(?:public|sign|authenticated)\/media\/(.+)$/);
    if (!match) return value;
    const path = decodeURIComponent(match[1]);
    if (path.split('/').some(part => !part || part === '.' || part === '..')) return value;
    return `${project.origin}/storage/v1/object/authenticated/media/${path.split('/').map(encodeURIComponent).join('/')}`;
  } catch { return value; }
};

/** A failed upload response may hide a successful write. Only accept a complete image. */
export const readStoredImage = async (storage: any, path: string, expectedHash?: string, strict = false) => {
  try {
    const { data, error } = await storage.download(path);
    if (error) {
      if (Number(error.statusCode || error.status) === 404 || /not.?found|does not exist/i.test(error.message || '')) return null;
      throw new Error('Storage could not be checked. Try recovery again shortly.');
    }
    if (!data) return null;
    const bytes = Buffer.from(await data.arrayBuffer());
    const size = readImageDimensions(bytes);
    const complete = bytes.length >= 24 && (
      (bytes.subarray(0, 8).toString('hex') === '89504e470d0a1a0a' && bytes.subarray(-12).toString('hex') === '0000000049454e44ae426082')
      || (bytes[0] === 0xff && bytes[1] === 0xd8 && bytes.at(-2) === 0xff && bytes.at(-1) === 0xd9)
      || (bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP' && bytes.readUInt32LE(4) + 8 === bytes.length)
    );
    if (!size || !complete || (expectedHash && imageSha256(bytes) !== expectedHash)) return null;
    return { size, bytes: bytes.length };
  } catch (error) {
    if (strict) throw error;
    return null;
  }
};

/** Only retries saving already generated bytes; never calls the image provider. */
export const saveGeneratedImage = async (
  upload: (upsert: boolean) => Promise<{ error: StorageError | null }>,
  pause: (ms: number) => Promise<void> = ms => new Promise(resolve => setTimeout(resolve, ms)),
): Promise<StorageError | null> => {
  let lastError: StorageError | null = null;
  for (let attempt = 0; attempt < 3; attempt++) {
    try { lastError = (await upload(attempt > 0)).error; }
    catch (error) { lastError = { message: error instanceof Error ? error.message : 'Storage connection failed' }; }
    if (!lastError) return null;
    const status = Number(lastError.statusCode || lastError.status);
    if (status && status !== 408 && status !== 429 && status < 500) break;
    if (attempt < 2) await pause(750 * (attempt + 1));
  }
  return lastError;
};
